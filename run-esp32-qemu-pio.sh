#!/usr/bin/env bash
set -Eeuo pipefail

# ============================================================
# PlatformIO -> Espressif QEMU
# Windows + WSL2
# Usage:
#   ~/run-esp32-qemu.sh /path/to/project [platformio_env]
#
# Optional overrides:
#   QEMU_BIN=/path/to/qemu-system-xtensa
#   QEMU_MACHINE=esp32
#   ESP_CHIP=esp32
# ============================================================

IDF_DIR="${IDF_DIR:-$HOME/esp/esp-idf}"
PROJECT_DIR="${1:-}"
REQUESTED_ENV="${2:-}"

info() { printf '\033[0;32m[INFO]\033[0m %s\n' "$*"; }
warn() { printf '\033[1;33m[WARN]\033[0m %s\n' "$*" >&2; }
die()  { printf '\033[0;31m[ERROR]\033[0m %s\n' "$*" >&2; exit 1; }

[[ -n "$PROJECT_DIR" ]] ||
    die "Укажи путь к проекту PlatformIO."

[[ -d "$PROJECT_DIR" ]] ||
    die "Каталог не найден: $PROJECT_DIR"

PROJECT_DIR="$(cd "$PROJECT_DIR" && pwd)"

[[ -f "$PROJECT_DIR/platformio.ini" ]] ||
    die "В каталоге нет platformio.ini: $PROJECT_DIR"

# Find PlatformIO CLI.
if command -v pio >/dev/null 2>&1; then
    PIO_CMD=(pio)
elif command -v platformio >/dev/null 2>&1; then
    PIO_CMD=(platformio)
else
    die "Не найден PlatformIO CLI в WSL. Установи PlatformIO Core и повтори."
fi

# Select environment: explicit argument or first [env:...].
if [[ -n "$REQUESTED_ENV" ]]; then
    ENV_NAME="$REQUESTED_ENV"
else
    ENV_NAME="$(
        sed -n \
          's/^[[:space:]]*\[env:\([^]]*\)\][[:space:]]*$/\1/p' \
          "$PROJECT_DIR/platformio.ini" | head -n 1
    )"
fi

[[ -n "$ENV_NAME" ]] ||
    die "Не найдено [env:...] в platformio.ini. Укажи environment вторым аргументом."

# Read board from the selected environment, falling back to [env].
BOARD="$(
    awk -v wanted="[env:$ENV_NAME]" '
      /^\[/ { section=$0 }
      section=="[env]" &&
        /^[[:space:]]*board[[:space:]]*=/ {
          v=$0
          sub(/^[^=]*=/, "", v)
          sub(/[;#].*/, "", v)
          gsub(/^[[:space:]]+|[[:space:]]+$/, "", v)
          default_board=v
        }
      section==wanted &&
        /^[[:space:]]*board[[:space:]]*=/ {
          v=$0
          sub(/^[^=]*=/, "", v)
          sub(/[;#].*/, "", v)
          gsub(/^[[:space:]]+|[[:space:]]+$/, "", v)
          print v
          found=1
          exit
        }
      END {
        if (!found && default_board != "") print default_board
      }
    ' "$PROJECT_DIR/platformio.ini" | tail -n 1
)"

[[ -n "$BOARD" ]] ||
    die "Не удалось определить board для environment '$ENV_NAME'."

# Map common PlatformIO board IDs to Espressif QEMU machine names.
case "$BOARD" in
    esp32-s3*|esp32s3*|lolin_s3)
        DEFAULT_CHIP="esp32s3"
        DEFAULT_MACHINE="esp32s3"
        QEMU_ARCH="xtensa"
        ;;
    esp32-c3*|esp32c3*|seeed_xiao_esp32c3)
        DEFAULT_CHIP="esp32c3"
        DEFAULT_MACHINE="esp32c3"
        QEMU_ARCH="riscv32"
        ;;
    esp32-c6*|esp32c6*)
        DEFAULT_CHIP="esp32c6"
        DEFAULT_MACHINE="esp32c6"
        QEMU_ARCH="riscv32"
        ;;
    esp32dev|esp32doit-devkit-v1|nodemcu-32s|esp-wrover-kit|esp32-poe|featheresp32|esp32)
        DEFAULT_CHIP="esp32"
        DEFAULT_MACHINE="esp32"
        QEMU_ARCH="xtensa"
        ;;
    *)
        die "Неизвестная плата '$BOARD'. Для нестандартной платы см. переменные QEMU_MACHINE и ESP_CHIP в инструкции ниже."
        ;;
esac

CHIP="${ESP_CHIP:-$DEFAULT_CHIP}"
MACHINE="${QEMU_MACHINE:-$DEFAULT_MACHINE}"
BUILD_DIR="$PROJECT_DIR/.pio/build/$ENV_NAME"

# Load ESP-IDF tools (esptool.py), if available.
if [[ -f "$IDF_DIR/export.sh" ]]; then
    # shellcheck disable=SC1091
    source "$IDF_DIR/export.sh" >/dev/null
fi

info "Проект:      $PROJECT_DIR"
info "Environment: $ENV_NAME"
info "Board:       $BOARD"
info "Chip:        $CHIP"
info "QEMU:        $MACHINE"

# Build using PlatformIO, not a separate idf.py build.
info "Собираем проект через PlatformIO..."
cd "$PROJECT_DIR"
"${PIO_CMD[@]}" run -e "$ENV_NAME"

[[ -d "$BUILD_DIR" ]] ||
    die "PlatformIO не создал каталог сборки: $BUILD_DIR"

# Locate flash_args generated by the ESP-IDF build.
FLASH_ARGS="$BUILD_DIR/flash_args"

if [[ ! -f "$FLASH_ARGS" ]]; then
    FLASH_ARGS="$(find "$BUILD_DIR" -maxdepth 4 -type f -name flash_args -print -quit)"
fi

[[ -n "$FLASH_ARGS" && -f "$FLASH_ARGS" ]] ||
    die "Не найден flash_args. Этот сценарий рассчитан на сборки, где PlatformIO/ESP-IDF создаёт flash_args. Для Arduino-проектов или нестандартной сборки нужна отдельная схема упаковки."

# Determine configured flash size; QEMU supports 2/4/8/16 MB images.
FLASH_SIZE="4MB"
for CONFIG_FILE in \
    "$PROJECT_DIR/sdkconfig" \
    "$BUILD_DIR/config/sdkconfig.h"
do
    [[ -f "$CONFIG_FILE" ]] || continue

    for SIZE in 16MB 8MB 4MB 2MB; do
        if grep -Eq \
          "(CONFIG_ESPTOOLPY_FLASHSIZE_${SIZE}=y|CONFIG_ESPTOOLPY_FLASHSIZE_${SIZE} 1)" \
          "$CONFIG_FILE"; then
            FLASH_SIZE="$SIZE"
            break 2
        fi
    done

    VALUE="$(
        sed -n 's/^CONFIG_ESPTOOLPY_FLASHSIZE="\{0,1\}\([^"]*\)"\{0,1\}$/\1/p' \
          "$CONFIG_FILE" | head -n 1
    )"

    case "$VALUE" in
        2MB|4MB|8MB|16MB) FLASH_SIZE="$VALUE"; break ;;
    esac
done

# Locate QEMU binary.
QEMU_NAME="qemu-system-$QEMU_ARCH"

if [[ -n "${QEMU_BIN:-}" ]]; then
    [[ -x "$QEMU_BIN" ]] || die "QEMU_BIN не найден или не исполняемый: $QEMU_BIN"
    QEMU="$QEMU_BIN"
elif command -v "$QEMU_NAME" >/dev/null 2>&1; then
    QEMU="$(command -v "$QEMU_NAME")"
else
    QEMU="$(
        find "$HOME/.espressif/tools" -type f -name "$QEMU_NAME" -perm -111 \
          -print -quit 2>/dev/null || true
    )"
fi

[[ -n "$QEMU" && -x "$QEMU" ]] ||
    die "Не найден $QEMU_NAME. Установи соответствующую сборку Espressif QEMU или укажи QEMU_BIN."

# Find esptool.py.
if command -v esptool.py >/dev/null 2>&1; then
    ESPTOOL=(esptool.py)
elif command -v esptool >/dev/null 2>&1; then
    ESPTOOL=(esptool)
else
    die "Не найден esptool.py. Проверь установку ESP-IDF или PlatformIO."
fi

FLASH_IMAGE="$BUILD_DIR/qemu_flash_image.bin"

info "Создаём образ SPI Flash размером $FLASH_SIZE..."
(
    cd "$BUILD_DIR"
    "${ESPTOOL[@]}" --chip "$CHIP" merge_bin \
        --fill-flash-size "$FLASH_SIZE" \
        -o "$FLASH_IMAGE" \
        "@$FLASH_ARGS"
)

[[ -s "$FLASH_IMAGE" ]] ||
    die "Образ QEMU не был создан."

info "Запускаем QEMU. Выход: Ctrl+C."
info "UART будет выведен в этот терминал."

exec "$QEMU" \
    -nographic \
    -machine "$MACHINE" \
    -drive "file=$FLASH_IMAGE,if=mtd,format=raw"
